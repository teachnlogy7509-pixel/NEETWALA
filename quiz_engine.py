from gemini import ask_gemini

def generate_neet_quiz(topic: str, count: int = 90):
    count = max(10, min(180, count))

    prompt = f"""
    केवल हिंदी में {count} मूल (original) NEET-स्तर के जीवविज्ञान MCQ तैयार करो।

    विषय: {topic}

    नियम:
    1. सभी प्रश्न हिंदी में हों।
    2. प्रत्येक प्रश्न में 4 विकल्प (A, B, C, D) हों।
    3. प्रत्येक प्रश्न के बाद सही उत्तर दें।
    4. प्रत्येक प्रश्न के बाद 1–2 लाइन की संक्षिप्त व्याख्या दें।
    5. प्रश्न NCERT आधारित NEET स्तर के हों।
    6. लगभग 20% प्रश्न Assertion–Reason प्रकार के हों।
    7. प्रश्नों की कठिनाई आसान, मध्यम और कठिन का मिश्रण हो।
    8. किसी भी पुस्तक के exact प्रश्न कॉपी न करें; केवल उसी स्तर के मूल प्रश्न बनाएं।

    आउटपुट स्पष्ट क्रमांक (1, 2, 3...) में दें।
    """

    return ask_gemini(prompt)
